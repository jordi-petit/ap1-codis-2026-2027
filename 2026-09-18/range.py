print("range(10)")
for x in range(10):
    print(x)

print("range(0, 10)")
for x in range(0, 10):
    print(x)

print("range(4, 10)")
for x in range(4, 10):
    print(x)

print("range(4, 10, 2)")
for x in range(4, 10, 2):
    print(x)

print("range(10, 0, -1)")
for x in range(10, 0, -1):
    print(x)
